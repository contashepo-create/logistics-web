-- v7 — دورة الموردين الكاملة (آمن التكرار)
--
--   مورّد ← فاتورة مشتريات بالضريبة ← سند دفع للمورّد ← رصيد وكشف حساب وأعمار ديون
--   كل الجداول معزولة بـ company_id + RLS، ولا وصول للمطوّر عليها (سياسة v5).
