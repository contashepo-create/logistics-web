   خصائص الأمان:
   - آمن عند إعادة التشغيل: يستخدم IF NOT EXISTS / CREATE OR REPLACE / DROP POLICY.
   - لا يحذف أي بيانات ولا يعدّل الحركات القديمة.
   - يعيد إصلاح ربط البيانات القديمة عبر user_id إن كان العمود موجوداً.
   - كل الجداول الجديدة معزولة بـ company_id وRLS.
   - يأخذ snapshot للأرصدة ثم ينشئ سنة جديدة مع أرصدة افتتاحية مستقلة.
